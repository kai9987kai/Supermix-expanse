def _fmt(v: Any) -> str:
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.4f}"
    return str(v)


def markdown(report: Dict[str, Any]) -> str:
    cols = ["archimedes", "expanse"] + list(report.get("ablations", {}).keys())
    lines = ["# Supermix Expanse vs Archimedes final", "",
             f"Expanse: `{report['expanse_path']}`  ", f"Archimedes: `{report['arch_path']}`  ",
             f"limit: {report['args'].get('limit')}  generated {report['created']}", "",
             "| metric | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]

    def val(col: str, getter: Callable[[Dict[str, Any]], Any]) -> str:
        try:
            if col in ("archimedes", "expanse"):
                return _fmt(getter({"dev": {s: e.get(col) for s, e in report["dev_loss"].items()},
                                    "gen": report.get("generation", {}).get(col, {})}))
            ab = report["ablations"][col]
            return _fmt(getter({"dev": {s: e.get("expanse") for s, e in ab.get("dev_loss", {}).items()},
                                "gen": ab.get("generation", {}).get("expanse", {})}))
        except (KeyError, TypeError, AttributeError):
            return "-"

    for s in te.SOURCES:
        if s not in report["dev_loss"]:
            continue
        lines.append(f"| dev loss {s} (common rows) | " + " | ".join(val(c, lambda d, s=s: d["dev"][s]["loss_common"]) for c in cols) + " |")
        lines.append(f"| dev loss {s} (own coverage) | " + " | ".join(val(c, lambda d, s=s: d["dev"][s]["loss_covered"]) for c in cols) + " |")
        lines.append(f"| coverage {s} | " + " | ".join(val(c, lambda d, s=s: d["dev"][s]["coverage"]) for c in cols) + " |")
    gen_rows = [("exact-answer accuracy", lambda d: d["gen"]["exact"]["accuracy"]),
                ("code pass rate", lambda d: d["gen"]["code"]["pass_rate"]),
                ("bio token-F1", lambda d: d["gen"]["bio"]["token_f1"]),
                ("PubMedQA accuracy", lambda d: d["gen"]["bio"]["pubmedqa_accuracy"]),
                ("PubMedQA majority baseline", lambda d: d["gen"]["bio"]["pubmedqa_majority_baseline"]),
                ("connectome exact match", lambda d: d["gen"]["connectome"]["exact_match"]),
                ("connectome answer hit", lambda d: d["gen"]["connectome"]["answer_hit"]),
                ("connectome token-F1", lambda d: d["gen"]["connectome"]["token_f1"])]
    for label, getter in gen_rows:
        lines.append(f"| {label} | " + " | ".join(val(c, getter) for c in cols) + " |")
    lines.append("")
    lines.append("Items per generation metric: " + json.dumps(report.get("items", {})))
    return "\n".join(lines) + "\n"


