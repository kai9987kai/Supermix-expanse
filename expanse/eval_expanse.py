@contextlib.contextmanager
def zero_gate(module) -> Iterator[None]:
    saved = module.gate.detach().clone()
    with torch.no_grad():
        module.gate.zero_()
    try:
        yield
    finally:
        with torch.no_grad():
            module.gate.copy_(saved)


@contextlib.contextmanager
def rewired_core(core, graph_args: Dict[str, Any], seed: int) -> Iterator[Dict[str, Any]]:
    import connectome_full as cf

    names = ("crow", "col", "val", "crow_t", "col_t", "val_t", "in_idx", "out_idx", "sign")
    saved = {n: getattr(core, n) for n in names}
    graph = cf.build_full_graph(graph_args["npz"], min_input_fraction=graph_args["threshold"], radius=graph_args["radius"])
    null = cf.rewired_graph(graph, seed=seed)
    del graph
    core.set_graph(null)
    info = {k: null["receipt"].get(k) for k in ("null", "null_seed", "edge_overlap_with_real", "abs_spectral_radius",
                                                "in_degree_changed_types", "value_sign_matches_source")}
    del null
    try:
        yield info
    finally:
        for n, t in saved.items():
            setattr(core, n, t)
        core._csr_cache = None


@contextlib.contextmanager
def donors_dead(model) -> Iterator[None]:
    alive = {li: [int(model.layers[li].mlp.expert_alive[s]) for s in slots] for li, slots in model.donor_slots().items()}
    model.set_donor_alive(False)
    try:
        yield
    finally:
        with torch.no_grad():
            for li, slots in model.donor_slots().items():
                for s, a in zip(slots, alive[li]):
                    model.layers[li].mlp.expert_alive[s] = a


