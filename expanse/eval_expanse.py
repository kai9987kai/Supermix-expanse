def dev_loss_block(runners: List[Runner], dev: Dict[str, List[Dict[str, Any]]], seq: int, batch: int,
                   also_cover: Tuple = ()) -> Dict[str, Any]:
    """``also_cover``: extra tokenizers whose coverage the "common" rows must also meet
    (ablations run Expanse alone but must report on the Archimedes-vs-Expanse common rows)."""
    res: Dict[str, Any] = {}
    cov = {rn.name: {s: covered(rn.tok, rows) for s, rows in dev.items()} for rn in runners}
    extra = [{s: covered(t, rows) for s, rows in dev.items()} for t in also_cover]
    for s, rows in dev.items():
        if not rows:
            continue
        both = [all(cov[rn.name][s][i] for rn in runners) and all(e[s][i] for e in extra) for i in range(len(rows))]
        entry: Dict[str, Any] = {"rows": len(rows), "rows_covered_by_all": int(sum(both))}
        for rn in runners:
            losses = rn.row_losses(rows, seq, batch)
            own = [l for l, c in zip(losses, cov[rn.name][s]) if c and l is not None]
            com = [l for l, c in zip(losses, both) if c and l is not None]
            entry[rn.name] = {
                "coverage": sum(cov[rn.name][s]) / len(rows),
                "loss_covered": sum(a for a, _ in own) / max(1, sum(n for _, n in own)) if own else None,
                "loss_common": sum(a for a, _ in com) / max(1, sum(n for _, n in com)) if com else None,
            }
        res[s] = entry
    return res


def generation_block(runners: List[Runner], items: Dict[str, List[Dict[str, Any]]], max_new: int,
                     code_verify: Optional[Callable]) -> Dict[str, Any]:
    import answer_check

    res: Dict[str, Any] = {}
    for rn in runners:
        r: Dict[str, Any] = {}
        t0 = time.time()
        # exact answers
        probs = items.get("exact", [])
        if probs:
            hit = chk = 0
            per_task: Dict[str, List[int]] = {}
            for p in probs:
                v = answer_check.check(p["user"], rn.generate(p["user"], max_new))
                if v is None:
                    continue
                chk += 1
                hit += int(v.correct)
                per_task.setdefault(p["task"], [0, 0])
                per_task[p["task"]][0] += int(v.correct)
                per_task[p["task"]][1] += 1
            r["exact"] = {"accuracy": hit / max(1, chk), "correct": hit, "checked": chk, "per_task": per_task}
        # code
        code = items.get("code", [])
        if code:
            if code_verify is None:
                r["code"] = {"unavailable": "teacher_data.verify_code_reply not importable"}
            else:
                ok = 0
                reasons: Counter = Counter()
                for row in code:
                    v = code_verify(rn.generate(row["user"], max_new), row["check"], require_explanation=False)
                    ok += int(v["ok"])
                    reasons[str(v.get("reason")).split(":")[0]] += 1
                r["code"] = {"pass_rate": ok / len(code), "passed": ok, "items": len(code), "reasons": dict(reasons)}
        # bio
        bio = items.get("bio", [])
        if bio:
            f1s = [token_f1(rn.generate(row["user"], max_new), row["assistant"]) for row in bio]
            r["bio"] = {"token_f1": sum(f1s) / len(f1s), "items": len(f1s)}
        # PubMedQA: every held-out question vs the expert label (not only the ones BioMedLM got
        # right, which are ~all "yes" -- see clean_bio_rows.py); majority baseline alongside
        pq = items.get("pubmedqa", [])
        if pq:
            hit, said = 0, Counter()
            for row in pq:
                m = re.match(r"^\W*(yes|no|maybe)\b", rn.generate(row["user"], max_new), re.I)
                d = m.group(1).lower() if m else "none"
                said[d] += 1
                hit += int(d == str(row["final_decision"]).lower())
            gold = Counter(str(row["final_decision"]).lower() for row in pq)
            r.setdefault("bio", {}).update({"pubmedqa_accuracy": hit / len(pq), "pubmedqa_items": len(pq),
                                            "pubmedqa_majority_baseline": max(gold.values()) / len(pq),
                                            "pubmedqa_answers": dict(said)})
        # connectome
        conn = items.get("connectome", [])
        if conn:
            em, f1s, hit, n_ans = 0, [], 0, 0
            for row in conn:
                reply = rn.generate(row["user"], max_new)
                em += int(norm_text(reply) == norm_text(row["assistant"]))
                f1s.append(token_f1(reply, row["assistant"]))
                if row.get("answer") not in (None, ""):
                    # the key fact (transmitter, count, top partner ...) stated as a whole word/number
                    n_ans += 1
                    ans = re.escape(str(row["answer"]).lower())
                    hit += int(re.search(rf"(?<![a-z0-9]){ans}(?![a-z0-9])", reply.lower()) is not None)
            r["connectome"] = {"exact_match": em / len(conn), "token_f1": sum(f1s) / len(f1s), "items": len(conn),
                               "answer_hit": hit / n_ans if n_ans else None}
        r["seconds"] = round(time.time() - t0, 1)
        res[rn.name] = r
        log(f"generation {rn.name}: " + json.dumps({k: (v if not isinstance(v, dict) else
                                                          {kk: vv for kk, vv in v.items() if kk != "per_task"})
                                                      for k, v in r.items()}))
    return res


