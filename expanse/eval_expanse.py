"""Evaluate Supermix Expanse against Archimedes final, with ablations.

    python expanse/eval_expanse.py                        # full report
    python expanse/eval_expanse.py --limit 4              # quick run (<= 4 rows/items per metric)

Metrics (both models, same rows)
    dev loss      per source on the training run's dev rows (recovered by key
                  from the Expanse receipt, else rebuilt with the trainer's
                  deterministic split), over the rows the model's tokenizer
                  covers without UNK -- coverage reported -- and over the rows
                  *both* models cover (the only like-for-like number)
    exact         ``probe_accuracy``-style: replay-style problems generated by
                  re-drawing every digit run of a replay question (kept only if
                  ``answer_check`` can parse it and it is not a training
                  prompt), greedy non-speculative decoding, ``answer_check.check``
    code          pass rate on the held-out code prompts, scored by the same
                  sandbox that filtered the teacher's rows
                  (``teacher_data.verify_code_reply``, explanation not required)
    bio           token-F1 vs the teacher's answer on held-out bio items, and
                  PubMedQA yes/no/maybe accuracy vs the expert ``final_decision``
    connectome    exact match, token-F1 and "answer hit" (the row's key fact
                  stated in the reply) on held-out *types*
Ablations (Expanse only; dev loss, plus generation with --ablation_gen)
    cns_full gate 0; cns_full on the degree-preserving rewired graph
    (``connectome_full.rewired_graph``); omni7 gate 0; donor experts dead;
    fly off.
Both models get the v48/v38 omni features (Archimedes was trained with them);
Expanse also gets its v7 state. Decoding is greedy with a KV cache
(``expanse_core.greedy_decode``), identical for both.

Writes ``checkpoints/eval_report.json`` and ``checkpoints/eval_report.md``.
"""

