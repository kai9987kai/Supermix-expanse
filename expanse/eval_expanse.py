# main
# ---------------------------------------------------------------------------
def main() -> int:
    ap = argparse.ArgumentParser(description="Evaluate Supermix Expanse vs Archimedes final")
    ap.add_argument("--expanse", default=str(PATHS["final"]))
    ap.add_argument("--arch", default=str(PATHS["arch_final"]))
    ap.add_argument("--limit", type=int, default=0, help="cap every metric's rows/items (quick runs)")
    ap.add_argument("--gen_limit", type=int, default=150, help="items per generation metric")
    ap.add_argument("--ablations", default="all", help="all | none | comma list of cns_gate0,cns_rewired,omni7_gate0,donors_dead,fly_off")
    ap.add_argument("--ablation_gen", action="store_true", help="also run generation metrics under each ablation")
    ap.add_argument("--max_new_tokens", type=int, default=96)
    ap.add_argument("--seq", type=int, default=128)
    ap.add_argument("--batch", type=int, default=8)
    ap.add_argument("--seed", type=int, default=None, help="default: the training seed from the receipt")
    ap.add_argument("--out", default=str(PATHS["checkpoints"] / "eval_report.json"))
    ap.add_argument("--md", default=None, help="default: --out with .md")
    ap.add_argument("--threads", type=int, default=8)
    args = ap.parse_args()
    torch.set_num_threads(args.threads)
    t0 = time.time()

    E, tokE, payE = ec.load_expanse(args.expanse)
    payE["state_dict"] = None
    receipt = payE.get("expanse") or {}
    training = receipt.get("training") or {}
    cargs = dict(training.get("corpus_args") or {})
    seed = int(args.seed if args.seed is not None else cargs.get("seed", training.get("seed", 2026)))
    A, tokA, _ = ec.load_archimedes(args.arch)
    A.eval()
    E.eval()
    log(f"loaded Expanse ({tokE.vocab_size} tokens) and Archimedes ({tokA.vocab_size} tokens) in {time.time() - t0:.1f}s")
    runners = [Runner("archimedes", A, tokA, False), Runner("expanse", E, tokE, True)]
    lim = args.limit or None

    # dev rows: the trainer's split (fly rows re-derived from the original fly core = Archimedes' fly_core)
    corpus = te.load_corpus(A.fly_core, fly_rows=int(cargs.get("fly_rows", 4000)), seed=seed,
                            dev_frac=float(cargs.get("dev_frac", 0.05)), dev_cap=int(cargs.get("dev_cap", 200)),
                            max_rows_per_source=int(cargs.get("max_rows_per_source", 6000)))
    dev_keys = training.get("dev_keys") or {}
    dev: Dict[str, List[Dict[str, Any]]] = {}
    for s in te.SOURCES:
        rows = corpus[s]["dev"]
        if dev_keys.get(s):
            want = set(dev_keys[s])
            rows = [r for r in rows if ec.row_key(r["user"], r["assistant"]) in want]
        dev[s] = rows[:lim] if lim else rows
    log("dev rows " + json.dumps({s: len(v) for s, v in dev.items()}))

    # generation items
    n_gen = min(args.gen_limit, lim) if lim else args.gen_limit
    items = {"exact": heldout_problems(n_gen, seed),
             "code": corpus["code"]["heldout"][:n_gen],
             "bio": [r for r in corpus["bio"]["heldout"] if r.get("task") == "bio_definition"][:n_gen],
             "pubmedqa": (ec.read_jsonl(PATHS["data"] / "pubmedqa_eval.jsonl")[:n_gen]
                          if (PATHS["data"] / "pubmedqa_eval.jsonl").exists() else []),
             "connectome": corpus["connectome"]["heldout"][:n_gen]}
    try:
        from teacher_data import verify_code_reply as code_verify
    except Exception as exc:  # pragma: no cover - reported, not fatal
        log(f"code sandbox unavailable: {exc}")
        code_verify = None
    log("generation items " + json.dumps({k: len(v) for k, v in items.items()}))

    report: Dict[str, Any] = {"expanse_path": args.expanse, "arch_path": args.arch, "args": vars(args), "seed": seed,
                              "created": time.strftime("%Y-%m-%d %H:%M:%S"),
                              "items": {k: len(v) for k, v in items.items()},
                              "dev_rows": {s: len(v) for s, v in dev.items()},
                              "expanse_gate_report": E.gate_report()}
    report["dev_loss"] = dev_loss_block(runners, dev, args.seq, args.batch)
    log("dev loss " + json.dumps({s: {k: v.get("loss_common") for k, v in e.items() if isinstance(v, dict)}
                                  for s, e in report["dev_loss"].items()}))
    report["generation"] = generation_block(runners, items, args.max_new_tokens, code_verify)

    # ablations on Expanse
    want = {"cns_gate0", "cns_rewired", "omni7_gate0", "donors_dead", "fly_off"}
    if args.ablations == "none":
        want = set()
    elif args.ablations != "all":
        want = {a.strip() for a in args.ablations.split(",") if a.strip()}
    exp_runner = runners[1]
    ablations: Dict[str, Any] = {}

    def run_ablation(name: str, ctx) -> None:
        t1 = time.time()
        with ctx as info:
            entry: Dict[str, Any] = {"dev_loss": dev_loss_block([exp_runner], dev, args.seq, args.batch,
                                                                  also_cover=(runners[0].tok,))}
            if info:
                entry["info"] = info
            if args.ablation_gen:
                entry["generation"] = generation_block([exp_runner], items, args.max_new_tokens, code_verify)
        entry["seconds"] = round(time.time() - t1, 1)
        ablations[name] = entry
        log(f"ablation {name}: " + json.dumps({s: e["expanse"]["loss_common"] for s, e in entry["dev_loss"].items()}))

    if "cns_gate0" in want and E.cns_full is not None:
        run_ablation("cns_gate0", zero_gate(E.cns_full))
    if "cns_rewired" in want and E.cns_full is not None:
        rec = (E.cns_meta or {}).get("receipt") or {}
        npz = Path(rec.get("npz") or PATHS["npz"])
        if not npz.exists():
            npz = PATHS["npz"]
        run_ablation("cns_rewired", rewired_core(E.cns_full, {"npz": npz, "threshold": float(rec.get("threshold", 0.0)),
                                                              "radius": float(rec.get("radius", 0.9))}, seed=0))
    if "omni7_gate0" in want and E.omni7 is not None:
        run_ablation("omni7_gate0", zero_gate(E.omni7))
    if "donors_dead" in want and E.donor_slots():
        run_ablation("donors_dead", donors_dead(E))
    if "fly_off" in want:
        exp_runner.extra_kw = {"use_fly": False}
        run_ablation("fly_off", contextlib.nullcontext())
        exp_runner.extra_kw = {}
    report["ablations"] = ablations
    report["seconds"] = round(time.time() - t0, 1)

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(ec.jsonable(report), indent=1), encoding="utf-8")
    md = Path(args.md) if args.md else out.with_suffix(".md")
    md.write_text(markdown(report), encoding="utf-8")
    log(f"wrote {out} and {md} in {report['seconds']:.0f}s")
    print(markdown(report))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
