DIGITS = re.compile(r"\d+")
WORD = re.compile(r"[a-z0-9]+")


def log(*a) -> None:
    print("[eval]", *a, flush=True)


# ---------------------------------------------------------------------------
# rows
# ---------------------------------------------------------------------------
def token_f1(pred: str, ref: str) -> float:
    p, r = WORD.findall(pred.lower()), WORD.findall(ref.lower())
    if not p or not r:
        return float(p == r)
    common = sum((Counter(p) & Counter(r)).values())
    if common == 0:
        return 0.0
    prec, rec = common / len(p), common / len(r)
    return 2 * prec * rec / (prec + rec)


def norm_text(s: str) -> str:
    return " ".join(s.lower().split()).rstrip(".")


def heldout_problems(n: int, seed: int) -> List[Dict[str, Any]]:
    """Replay-style problems no model trained on: every digit run re-drawn."""
    import answer_check

    replay = ec.load_replay()
    seen = {r["user"] for r in replay}
    rng = random.Random(seed)
    order = list(range(len(replay)))
    rng.shuffle(order)
    out: List[Dict[str, Any]] = []
    for i in order:
        if len(out) >= n:
            break
        r = replay[i]
        if not DIGITS.search(r["user"]):
            continue
        for _ in range(4):
            def redraw(m: re.Match) -> str:
                k = len(m.group(0))
                return str(rng.randint(0, 9)) if k == 1 else str(rng.randint(10 ** (k - 1), 10 ** k - 1))
            q = DIGITS.sub(redraw, r["user"])
            if q not in seen and answer_check.parse_question(q) is not None:
                seen.add(q)
                out.append({"user": q, "task": r.get("task", "?")})
                break
    return out


def covered(tok, rows) -> List[bool]:
    return [text_utils.UNK not in tok.encode_turn(r["user"], r["assistant"])[0] for r in rows]


# ---------------------------------------------------------------------------
# model wrappers
# ---------------------------------------------------------------------------
class Runner:
    """One model + tokenizer + the prompt-constant inputs it needs."""

    def __init__(self, name: str, model, tok, is_expanse: bool):
        self.name, self.model, self.tok, self.is_expanse = name, model, tok, is_expanse
        self.extra_kw: Dict[str, Any] = {}

    def kwargs(self, users: List[str]) -> Dict[str, Any]:
        kw: Dict[str, Any] = {"omni_features": ec.arch.OmniCore.featurize(users)}
        if self.is_expanse and self.model.omni7 is not None:
            kw["omni7_state"] = self.model.omni7_state_for(users)
        kw.update(self.extra_kw)
        return kw

    @torch.no_grad()
    def row_losses(self, rows: List[Dict[str, Any]], seq: int, batch: int) -> List[Optional[Tuple[float, int]]]:
        """(sum CE over reply tokens, n tokens) per row; None if over-length."""
        self.model.eval()
        out: List[Optional[Tuple[float, int]]] = [None] * len(rows)
        x, y, pl, meta, _ = te.encode_rows(rows, self.tok, seq)
        keep = [i for i, r in enumerate(rows) if len(self.tok.encode_turn(r["user"], r["assistant"])[0]) <= seq]
        for b in range(0, x.shape[0], batch):
            xb, yb = x[b:b + batch], y[b:b + batch]
            lg = self.model(xb, return_mtp=False, **self.kwargs([r["user"] for r in meta[b:b + batch]])).logits
            ce = F.cross_entropy(lg[:, :-1].reshape(-1, lg.shape[-1]), yb[:, 1:].reshape(-1), reduction="none").view(xb.shape[0], -1)
            m = yb[:, 1:] != -100
            for j in range(xb.shape[0]):
                out[keep[b + j]] = (float(ce[j][m[j]].sum()), int(m[j].sum()))
        return out

    @torch.no_grad()
    def generate(self, user: str, max_new: int) -> str:
        ids, _ = self.tok.encode_turn(user, None)
        new = ec.greedy_decode(self.model, torch.tensor([ids]), max_new_tokens=max_new, **self.kwargs([user]))
        return self.tok.decode(new).strip()


